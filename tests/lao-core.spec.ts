import { describe, expect, it } from 'vitest'
import { MemoryRepositories, ticketStage, canRetry, assertTransition } from '../src/core/index.ts'
import { lao } from './fixtures/lao.ts'

describe('LAO acceptance and authorization', () => {
  it('retains Trigger, Thread, Decision and Mandate without starting an Agent', () => {
    const h = lao(), t = h.accept()
    expect(t.lifecycle?.status).toBe('QUEUED')
    expect(t.assignments).toEqual([])
    expect(h.starts).toEqual([])
    expect(h.repo.decisions.get(t.decisionId)?.mandate).toEqual(t.mandate)
    expect(h.repo.workflow!.history(t.id).map(item => item.to)).toEqual(['NEW', 'QUEUED'])
    expect(h.repo.workflow!.domainEvents().map(item => item.type)).toContain('decision.recorded')
  })
  it('rejects acceptance without LAO metadata and rolls back the decision', () => {
    const h = lao(); h.engine.receive(h.trigger())
    expect(() => h.engine.decide('event-1', { kind: 'accept', title: 'a', scope: 'b', reason: 'c' })).toThrow('metadata')
    expect(h.repo.tickets.list()).toHaveLength(0)
  })
  it('binds one Ticket per Issue across events and refuses reassignment', () => {
    const h = lao(), t = h.accept()
    const again = h.accept(value => { value.task!.issue.revision = 'v2' }, h.trigger('event-2'))
    expect(again.id).toBe(t.id)
    expect(h.repo.tickets.list()).toHaveLength(1)
    expect(() => h.repo.workflow!.bindIssue(t.lifecycle!.issue, 'other')).toThrow('already bound')
    expect(h.starts).toEqual([])
  })
  it('keeps different source instances distinct', () => {
    const h = lao(); h.accept()
    const event = h.trigger('other-event'); event.source = 'ding:team-b'; event.threads = [{ source: event.source, id: 'issue-1' }]
    h.accept(value => { value.task!.issue.source = event.source }, event)
    expect(h.repo.tickets.list()).toHaveLength(2)
  })
  it('records closed issues without execution or approval', () => {
    const h = lao(), t = h.accept(value => { value.task!.issue.closed = true })
    expect(t.lifecycle?.status).toBe('CANCELLED')
    expect(() => h.running(t.id)).toThrow('not queued')
    expect(h.starts).toEqual([])
  })
  it('requires approval and records who approved under the current policy', () => {
    const h = lao(), t = h.accept(value => { value.task!.policy.approvalRequired = true })
    expect(() => h.running(t.id)).toThrow('not queued')
    const before = h.repo.workflow!.history(t.id)
    expect(() => h.engine.approveTask(t.id, '', 'approved')).toThrow('actor')
    expect(h.repo.workflow!.history(t.id)).toEqual(before)
    expect(h.engine.approveTask(t.id, 'alice', 'Approved scoped edits').lifecycle?.status).toBe('QUEUED')
    expect(h.repo.workflow!.history(t.id).some(e => e.kind === 'approval' && e.actor === 'alice' && e.decision === 'approved')).toBe(true)
  })
  it('records rejected execution approval and never launches the rejected task', () => {
    const h = lao(), t = h.accept(v => { v.task!.policy.approvalRequired = true })
    expect(h.engine.rejectTask(t.id, 'alice', 'Out of scope').lifecycle?.status).toBe('CANCELLED')
    expect(h.repo.workflow!.history(t.id).some(e => e.kind === 'approval' && e.decision === 'rejected')).toBe(true)
    expect(h.starts).toEqual([])
  })
  it('refuses assignment when the policy changed since acceptance', () => {
    const h = lao(), t = h.accept(); h.setPolicy('policy-2')
    expect(() => h.running(t.id)).toThrow('conditions')
    expect(h.repo.tickets.get(t.id)?.assignments).toEqual([])
  })
  it('rolls back the entire acceptance if task metadata is invalid', () => {
    const h = lao()
    expect(() => h.accept(v => { v.task!.policy.retryLimit = -1 })).toThrow('metadata')
    expect(h.repo.tickets.list()).toEqual([])
    expect(h.repo.workflow!.findIssue(h.outcome().task!.issue)).toBeUndefined()
  })
})

describe('execution, verification and review are separate', () => {
  it('requires execution evidence and revision-bound review; a worker report cannot mark DONE', () => {
    const h = lao(), t = h.accept(), assignment = h.running(t.id)
    expect(() => h.engine.report(t.id, { state: 'ready', summary: 'I finished' })).toThrow('evidence')
    expect(h.engine.recordExecution(t.id, h.result(assignment)).lifecycle?.status).toBe('REVIEW')
    expect(ticketStage(h.repo.tickets.get(t.id)!)).toEqual({ stage: 'person', action: 'review' })
    expect(() => h.engine.reviewTask(t.id, h.review(assignment))).toThrow('Verification')
    h.verify(t.id, assignment)
    expect(() => h.engine.reviewTask(t.id, { ...h.review(assignment), artifactRevision: 'stale' })).toThrow('artifacts')
    expect(h.engine.reviewTask(t.id, h.review(assignment)).lifecycle?.status).toBe('DONE')
    expect(h.repo.workflow!.history(t.id).at(-1)?.to).toBe('DONE')
    expect(() => h.engine.retryTask(t.id, 'alice', 'again')).toThrow('not retryable')
  })
  it.each([{ exitCode: 1, terminal: 'success' as const }, { exitCode: 0, terminal: 'error' as const }])('fails for error terminal evidence %j', patch => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    expect(h.engine.recordExecution(t.id, { ...h.result(a), ...patch }).lifecycle?.status).toBe('FAILED')
    expect(() => h.engine.reviewTask(t.id, h.review(a))).toThrow()
  })
  it('replays identical process receipts without losing verification or repeating transitions', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.assignmentStarted(t.id, a)
    h.engine.recordExecution(t.id, h.result(a)); h.verify(t.id, a)
    const before = h.repo.workflow!.history(t.id)
    expect(h.engine.recordExecution(t.id, h.result(a)).lifecycle?.result?.verification).toBe('not_required')
    expect(h.repo.workflow!.history(t.id)).toEqual(before)
    expect(() => h.engine.recordExecution(t.id, { ...h.result(a), artifactRevision: 'changed' })).toThrow('Conflicting')
  })
  it('rejects stale starts and results without changing the current assignment', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    expect(() => h.engine.assignmentStarted(t.id, 'old')).toThrow('Stale')
    expect(() => h.engine.recordExecution(t.id, h.result('old'))).toThrow('Stale')
    expect(h.repo.tickets.get(t.id)?.assignments.at(-1)?.id).toBe(a)
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('RUNNING')
  })
  it('does not auto-finish when a related source Thread closes', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.bindThread(t.id, { source: 'github', id: 'pr-1' }, true)
    h.engine.threadClosed({ source: 'github', id: 'pr-1' }, 'merged', '2026-11-03T01:00:00.000Z')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('RUNNING')
    h.engine.recordExecution(t.id, h.result(a))
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('REVIEW')
  })
  it('does not wake completed tasks when their source receives another human update', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.recordExecution(t.id, h.result(a)); h.verify(t.id, a); h.engine.reviewTask(t.id, h.review(a))
    h.engine.receive(h.trigger('later')); h.engine.evaluateDue()
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('DONE')
    expect(h.starts).toHaveLength(1)
  })
  it('refuses failed verification and records rejected review separately', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.recordExecution(t.id, h.result(a))
    h.engine.recordVerification(t.id, { ...h.review(a), state: 'failed' })
    expect(() => h.engine.reviewTask(t.id, h.review(a))).toThrow('Verification')
    expect(h.engine.reviewTask(t.id, { ...h.review(a), approved: false }).lifecycle?.status).toBe('BLOCKED')
    expect(h.repo.workflow!.history(t.id).some(e => e.decision === 'rejected')).toBe(true)
  })
})

describe('safe interruption, cancellation and retry', () => {
  it('blocks interrupted processes without automatically rerunning or releasing their assignment', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.assignmentInterrupted(t.id, a)
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('BLOCKED')
    expect(canRetry(h.repo.tickets.get(t.id)!)).toBe(false)
    expect(() => h.engine.retryTicket(t.id)).toThrow('confirmed stopped')
    expect(h.starts).toHaveLength(1)
    h.engine.confirmProcessStopped(t.id, a, 'Runtime confirmed process absent')
    expect(h.engine.retryTask(t.id, 'alice', 'Inspect worktree and retry').lifecycle?.status).toBe('QUEUED')
    expect(h.starts).toHaveLength(1)
    expect(h.repo.workflow!.history(t.id).some(e => e.kind === 'retry')).toBe(true)
  })
  it('keeps cancellation pending until termination is confirmed', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    const pending = h.engine.cancelTask(t.id, 'alice', 'No longer needed')
    expect(pending.lifecycle?.status).toBe('RUNNING')
    expect(pending.lifecycle?.cancelRequested?.actor).toBe('alice')
    expect(h.stops).toEqual([a])
    h.engine.cancelTask(t.id, 'alice', 'No longer needed')
    expect(h.stops).toEqual([a])
    expect(h.engine.confirmProcessStopped(t.id, a, 'Process group stopped').lifecycle?.status).toBe('CANCELLED')
  })
  it('does not accept a delayed start after cancellation', () => {
    const h = lao(), t = h.accept()
    const a = h.engine.assignTask(t.id, 'a', 'claude-code', '/worktree').assignments.at(-1)!.id
    h.engine.cancelTask(t.id, 'alice', 'cancel')
    expect(() => h.engine.assignmentStarted(t.id, a)).toThrow('cancelled')
    h.engine.confirmProcessStopped(t.id, a, 'Launch worker confirmed stopped')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('CANCELLED')
  })
  it('retains previous execution evidence after a retry clears the current result', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.engine.recordExecution(t.id, { ...h.result(a), exitCode: 1 })
    h.engine.retryTask(t.id, 'alice', 'Retry transient failure')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.result).toBeUndefined()
    expect(h.repo.workflow!.history(t.id).find(e => e.evidence)?.evidence).toMatchObject({ exitCode: 1, assignmentId: a })
  })
  it('enforces retry limits without silently launching', () => {
    const h = lao(), t = h.accept(v => { v.task!.policy.retryLimit = 0 }), a = h.running(t.id)
    h.engine.recordExecution(t.id, { ...h.result(a), exitCode: 1 })
    expect(() => h.engine.retryTask(t.id, 'alice', 'retry')).toThrow('limit')
    expect(h.starts).toHaveLength(1)
  })
  it('rolls back source bindings, events and nested changes together', () => {
    const repo = new MemoryRepositories(), h = lao(repo)
    expect(() => repo.atomic(() => { h.accept(); throw new Error('rollback') })).toThrow('rollback')
    expect(repo.tickets.list()).toEqual([])
    expect(repo.workflow.findIssue(h.outcome().task!.issue)).toBeUndefined()
    expect(repo.workflow.domainEvents()).toEqual([])
  })
  it.each([['NEW', 'DONE'], ['RUNNING', 'DONE'], ['FAILED', 'DONE'], ['DONE', 'RUNNING'], ['CANCELLED', 'QUEUED']] as const)('rejects %s -> %s', (from, to) => {
    expect(() => assertTransition(from, to)).toThrow('Illegal')
  })
})

describe('observed source revisions', () => {
  it('records closure without overwriting accepted input and prevents queued launch', () => {
    const h = lao(), t = h.accept()
    h.accept(v => { v.task!.issue.revision = 'v2'; v.task!.issue.closed = true }, h.trigger('close-event'))
    const current = h.repo.tickets.get(t.id)!
    expect(current.lifecycle?.issue.closed).toBe(false)
    expect(current.lifecycle?.observedIssue?.closed).toBe(true)
    expect(current.lifecycle?.status).toBe('CANCELLED')
    expect(() => h.running(t.id)).toThrow('not queued')
    expect(h.repo.workflow!.history(t.id).some(e => e.kind === 'source-update' && e.issueSnapshot?.closed)).toBe(true)
    expect(h.starts).toEqual([])
  })
  it('requests stop on source closure and waits for termination confirmation', () => {
    const h = lao(), t = h.accept(), a = h.running(t.id)
    h.accept(v => { v.task!.issue.revision = 'v2'; v.task!.issue.closed = true }, h.trigger('running-close'))
    expect(h.stops).toEqual([a])
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('RUNNING')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.cancelRequested).toBeTruthy()
    h.engine.confirmProcessStopped(t.id, a, 'Confirmed process exit')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('CANCELLED')
  })
  it('blocks revised queued input for reassessment and rejects conflicting revisions', () => {
    const h = lao(), t = h.accept()
    h.accept(v => { v.task!.issue.revision = 'v2'; v.task!.issue.description = 'New scope' }, h.trigger('changed'))
    expect(h.repo.tickets.get(t.id)?.lifecycle?.status).toBe('BLOCKED')
    expect(h.repo.tickets.get(t.id)?.lifecycle?.issue.description).toBe('Fix typo')
    expect(() => h.accept(v => { v.task!.issue.revision = 'v2' }, h.trigger('conflict'))).toThrow('Conflicting')
    expect(h.repo.tickets.list()).toHaveLength(1)
  })
})
