import { test,expect } from '@playwright/test'
import type { Employee,Project,ManagementAudit } from '../src/api.ts'
import { localWorkspace } from './local-workspace.ts'
let workspace:Awaited<ReturnType<typeof localWorkspace>>
test.beforeAll(async()=>{workspace=await localWorkspace()})
test.afterAll(async()=>{await workspace?.stop()})
test('Owner manages projects and employees with explicit versioned confirmations and durable audit',async({page})=>{
 await page.goto(workspace.address)
 await page.getByLabel('本地访问凭证').fill(workspace.token)
 await page.getByRole('button',{name:'连接工作空间',exact:true}).click()
 await page.getByRole('heading',{name:'概览',exact:true}).waitFor()
 const navigation=page.getByRole('navigation',{name:'主导航'})
 await navigation.getByRole('link',{name:'项目空间'}).click()
 await page.getByLabel('项目 ID',{exact:true}).fill('managed-project')
 await page.getByLabel('项目名称',{exact:true}).fill('浏览器文档项目')
 await page.getByLabel('业务负责人',{exact:true}).fill('business-owner')
 await page.getByLabel('仓库路径',{exact:true}).fill(workspace.repositoryPath)
 await page.getByLabel('工作树根目录',{exact:true}).fill(workspace.worktreeRoot)
 await page.getByLabel('允许任务类型',{exact:true}).fill('documentation')
 await page.getByLabel('操作原因',{exact:true}).fill('批准注册本地测试项目')
 await page.getByRole('button',{name:'预览创建',exact:true}).click()
 const preview=page.getByRole('region',{name:'操作确认预览'})
 await expect(preview).toContainText(workspace.repositoryPath)
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect(page.getByRole('cell',{name:'浏览器文档项目',exact:true})).toBeVisible()
 const projects=async()=>await workspace.request('/projects') as Project[]
 expect((await projects())[0]).toMatchObject({id:'managed-project',ownerId:'business-owner',archived:false,version:1})
 await navigation.getByRole('link',{name:'AI 员工',exact:true}).click()
 await page.getByLabel('员工 ID',{exact:true}).fill('managed-writer')
 await page.getByLabel('员工名称',{exact:true}).fill('浏览器写作助手')
 await page.getByLabel('员工岗位',{exact:true}).fill('Technical Writer')
 await page.getByLabel('职责',{exact:true}).fill('维护文档')
 await page.getByLabel('能力',{exact:true}).fill('documentation')
 await page.getByLabel('绑定项目 浏览器文档项目',{exact:true}).check()
 await page.getByLabel('操作原因',{exact:true}).fill('批准建立员工，先保持停用')
 await page.getByRole('button',{name:'预览创建',exact:true}).click()
 await expect(preview).toContainText('managed-project')
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect(page.getByRole('cell',{name:'浏览器写作助手',exact:true})).toBeVisible()
 const employees=async()=>await workspace.request('/employees') as Employee[]
 expect((await employees())[0]).toMatchObject({id:'managed-writer',enabled:false,version:1})
 await page.getByRole('button',{name:'编辑员工 浏览器写作助手',exact:true}).click()
 await page.getByLabel('操作原因',{exact:true}).fill('明确批准文档员工接单')
 await page.getByRole('button',{name:'预览启用',exact:true}).click()
 expect((await employees())[0]?.enabled).toBe(false)
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect.poll(async()=>(await employees())[0]?.enabled).toBe(true)
 await expect(page.getByLabel('职责',{exact:true})).toBeDisabled()
 await page.getByLabel('操作原因',{exact:true}).fill('停用后调整能力范围')
 await page.getByRole('button',{name:'预览停用',exact:true}).click()
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect(page.getByLabel('职责',{exact:true})).toBeEnabled()
 await page.getByLabel('员工名称',{exact:true}).fill('升级后的写作助手')
 await page.getByLabel('职责',{exact:true}).fill('维护经批准的项目文档')
 await page.getByLabel('操作原因',{exact:true}).fill('在停用状态下修改职责')
 await page.getByRole('button',{name:'预览更新',exact:true}).click()
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect(page.getByRole('cell',{name:'升级后的写作助手',exact:true})).toBeVisible()
 expect((await employees())[0]).toMatchObject({enabled:false,version:4,responsibilities:['维护经批准的项目文档']})
 await expect(page.getByRole('region',{name:'员工变更历史'})).toContainText('browser-owner')
 await navigation.getByRole('link',{name:'项目空间'}).click()
 await page.getByRole('button',{name:'编辑项目 浏览器文档项目',exact:true}).click()
 await expect(page.getByLabel('仓库路径',{exact:true})).toBeDisabled()
 await page.getByLabel('项目名称',{exact:true}).fill('已更新的文档项目')
 await page.getByLabel('操作原因',{exact:true}).fill('更新业务名称')
 await page.getByRole('button',{name:'预览更新',exact:true}).click()
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect(page.getByRole('cell',{name:'已更新的文档项目',exact:true})).toBeVisible()
 await page.getByLabel('操作原因',{exact:true}).fill('结束测试项目，保留历史')
 await page.getByRole('button',{name:'预览归档',exact:true}).click()
 await expect(preview).toContainText('不影响运行中任务')
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect.poll(async()=>(await projects())[0]?.archived).toBe(true)
 const employeeAudit=await workspace.request('/employees/managed-writer/history') as {items:ManagementAudit[]}
 const projectAudit=await workspace.request('/projects/managed-project/history') as {items:ManagementAudit[]}
 expect(employeeAudit.items).toHaveLength(4);expect(projectAudit.items).toHaveLength(3)
 expect(employeeAudit.items.every(item=>item.actorId==='browser-owner'&&item.reason.length>0)).toBe(true)
 expect((await workspace.request('/executions') as {items:unknown[]}).items).toHaveLength(0)
 await navigation.getByRole('link',{name:'执行中心'}).click();await expect(page.getByRole('heading',{name:'执行中心',exact:true})).toBeVisible()
 await expect(page.getByText('暂无记录',{exact:true})).toBeVisible()
 await navigation.getByRole('link',{name:'AI 员工',exact:true}).click()
 await page.getByRole('button',{name:'编辑员工 升级后的写作助手',exact:true}).click()
 await expect(page.getByRole('region',{name:'员工变更历史'})).toContainText('在停用状态下修改职责')
 await expect(page.getByLabel('绑定项目 已更新的文档项目',{exact:true})).toBeChecked()
 await page.getByLabel('员工名称',{exact:true}).fill('归档项目后仍可编辑的助手')
 await page.getByLabel('操作原因',{exact:true}).fill('仅修改名称，保留已归档项目历史绑定')
 await page.getByRole('button',{name:'预览更新',exact:true}).click()
 await preview.getByRole('button',{name:'确认提交'}).click()
 await expect.poll(async()=>(await employees())[0]?.name).toBe('归档项目后仍可编辑的助手')
 expect((await employees())[0]?.projectIds).toEqual(['managed-project'])
 await page.screenshot({path:'test-results/web/employees-management.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:'test-results/web/employees-management-mobile.png',fullPage:true})
 expect(workspace.credentialAbsentFromOutput()).toBe(true)
})
